// Helper to format JS objects into clean TypeScript literal
function formatObject(obj, indent = 2) {
  const spaces = ' '.repeat(indent);
  const nextSpaces = ' '.repeat(indent + 2);
  let str = '{\n';
  for (const [key, val] of Object.entries(obj)) {
    str += `${nextSpaces}${key}: `;
    if (typeof val === 'string') {
      str += JSON.stringify(val);
    } else if (typeof val === 'number' || typeof val === 'boolean') {
      str += val;
    } else if (Array.isArray(val)) {
      str += '[\n';
      for (const item of val) {
        if (typeof item === 'string') {
          str += `${nextSpaces}  ${JSON.stringify(item)},\n`;
        } else if (typeof item === 'object') {
          str += `${nextSpaces}  ${formatObject(item, indent + 4)},\n`;
        } else {
          str += `${nextSpaces}  ${item},\n`;
        }
      }
      str += `${nextSpaces}]`;
    } else if (typeof val === 'object' && val !== null) {
      str += formatObject(val, indent + 2);
    }
    str += ',\n';
  }
  str += `${spaces}}`;
  return str;
}

